/* Which zero-meter ending applies. */
AD.zeroEnding = key => 'zero-' + key;

/* Build the final scorecard shown on the ending screen. */
AD.scoreRun = function (run, endingId) {
  // THE BOREDOM GATE. A win only counts if the easily-bored President was still
  // entertained at the end (run.fun above the difficulty floor). Fall below it
  // and the victory curdles into THE ABDICATION, he had it, and could not be
  // bothered to keep it.
  if (AD.ENDINGS[endingId] && AD.ENDINGS[endingId].win && AD.entertained && !AD.entertained(run)) {
    endingId = 'bored';
  }
  const e = AD.ENDINGS[endingId];
  const pillars = Object.keys(run.locked).length;
  const mult = { rookie: 0.7, standard: 1, historic: 1.5 }[run.difficulty] || 1;
  const score = Math.round((
    run.authority * 10 +
    pillars * 120 +
    run.month * 6 +
    run.doctrines.length * 40 +
    (run.term - 1) * 300 +
    AD.clauseScore(run) +                       // 150/clause, +1200 for the full set
    (e && e.win ? 900 : 0)
  ) * mult);
  return {
    endingId, win: !!(e && e.win),
    president: run.president, party: run.party, color: run.color,
    portrait: run.portrait, difficulty: run.difficulty,
    months: run.month, maxMonths: run.maxMonths, term: run.term,
    authority: run.authority, pillars: pillars,
    pillarNames: Object.keys(run.locked).map(k => AD.faction(k).pillar),
    doctrines: run.doctrines.slice(),
    seed: run.seed || null,
    clauses: (run.clauses || []).slice(),
    clausesBroken: AD.clauseCount(run),
    fullSet: AD.allClausesBroken(run),
    cash: Math.round(run.cash * 10) / 10,
    inherited: !!(run.legacy && Object.keys(run.legacy.mods || {}).length),
    // --- the record of HOW you governed, for the generated dossier ---
    sacked: (run.senate || []).filter(s => s.gone).length,
    sackedName: (run.senate || []).filter(s => s.gone).map(s => 'Sen. ' + s.last + ' of ' + s.state)[0] || null,
    caucusAvg: (AD.senateSummary ? AD.senateSummary(run).avgOwn : null),
    judgesPacked: (run.judges || []).filter(j => j.appointee).length,
    packedName: (run.judges || []).filter(j => j.appointee).map(j => j.name)[0] || null,
    outletsOwned: (run.press || []).filter(o => o.owned).length,
    ownedName: (run.press || []).filter(o => o.owned).map(o => o.name)[0] || null,
    warsDeclared: (run.stats && run.stats.wars) || 0,
    warLog: (run.warLog || []).slice(),
    rallies: (run.stats && run.stats.rallies) || 0,
    calls: (run.stats && run.stats.calls) || 0,
    bought: (run.assets || []).length,
    renos: (run.renos || []).length,
    hasCasino: (run.renos || []).indexOf('casino') !== -1,
    pardons: (run.pardoned || []).length,
    pardonSaints: (run.pardoned || []).filter(id => { const p = AD.pardonById && AD.pardonById(id); return p && p.saint; }).length,
    topPardon: (run.pardoned || []).map(id => AD.pardonById && AD.pardonById(id)).filter(p => p && !p.saint).map(p => p.name)[0] || null,
    cayHeat: (AD.cayHeat ? AD.cayHeat(run) : 0),
    cayStage: (run.cay && run.cay.stage) || 0,
    cabinetChurn: (run.stats && run.stats.cabinetChurn) || 0,
    truthIndex: (run.stats && run.stats.truthIndex != null) ? run.stats.truthIndex : 50,
    score: score,
    stamp: Date.now()
  };
};
